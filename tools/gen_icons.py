#!/usr/bin/env python3
"""Draws the menu icons and the "Video not found" message, and writes
main/icons.h (8-bit alpha masks).

Icons are drawn 4x larger with Pillow and scaled down, so edges come out
anti-aliased. Run again after changing a shape:  python3 tools/gen_icons.py
Also writes tools/icons_preview.png to look at them.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

SIZE = 56          # icon size on screen (px)
K = 4              # supersampling
S = SIZE * K       # drawing canvas
W = 15             # stroke width on the canvas

ROOT = Path(__file__).resolve().parent.parent


def canvas():
    img = Image.new("L", (S, S), 0)
    return img, ImageDraw.Draw(img)


def speaker(d):
    d.rectangle((24, 84, 70, 140), fill=255)
    d.polygon([(66, 84), (118, 40), (118, 184), (66, 140)], fill=255)


def sound_on():
    img, d = canvas()
    speaker(d)
    for r in (46, 82):
        d.arc((112 - r, 112 - r, 112 + r, 112 + r), -50, 50, fill=255, width=W)
    return img


def sound_off():
    img, d = canvas()
    speaker(d)
    d.line((146, 82, 204, 142), fill=255, width=W + 2)
    d.line((146, 142, 204, 82), fill=255, width=W + 2)
    return img


def next_video():
    img, d = canvas()
    d.polygon([(40, 44), (150, 112), (40, 180)], fill=255)
    d.rectangle((158, 44, 184, 180), fill=255)
    return img


def arrow_head(d, tip, direction, size=34):
    """Filled triangle pointing along `direction` (unit vector) with its tip at `tip`."""
    (x, y), (dx, dy) = tip, direction
    bx, by = x - dx * size, y - dy * size
    px, py = -dy * size * 0.75, dx * size * 0.75
    d.polygon([(x, y), (bx + px, by + py), (bx - px, by - py)], fill=255)


def repeat_loop(d):
    """Rounded loop with an arrow on the top (right) and bottom (left) runs."""
    d.rounded_rectangle((26, 62, 198, 162), radius=40, outline=255, width=W)
    # Gaps where the arrows sit: top-right and bottom-left.
    d.rectangle((150, 40, 224, 84), fill=0)
    d.rectangle((0, 140, 74, 184), fill=0)
    arrow_head(d, (192, 69), (1, 0), size=42)
    arrow_head(d, (32, 155), (-1, 0), size=42)


def repeat_all():
    img, d = canvas()
    repeat_loop(d)
    return img


def repeat_one():
    img, d = canvas()
    repeat_loop(d)
    # A small "1" in the middle of the loop.
    d.rectangle((103, 88, 123, 138), fill=255)
    d.polygon([(103, 88), (123, 88), (92, 104), (92, 98)], fill=255)
    return img


MESSAGE = "Video not found"
MESSAGE_PX = 34  # font size on screen
FONT = ROOT / "tools" / "fonts" / "BeVietnamPro-Bold.ttf"  # SIL Open Font License


def message():
    """White-on-transparent text, cropped, width padded to a multiple of 4
    (the panel takes columns in groups of 4)."""
    font = ImageFont.truetype(str(FONT), MESSAGE_PX * K)
    left, top, right, bottom = font.getbbox(MESSAGE)
    big = Image.new("L", (right - left + 2 * K, bottom - top + 2 * K), 0)
    ImageDraw.Draw(big).text((K - left, K - top), MESSAGE, font=font, fill=255)
    w = -(-big.width // K)
    h = -(-big.height // K)
    small = big.resize((w, h), Image.LANCZOS)
    padded = Image.new("L", ((w + 3) // 4 * 4, h), 0)
    padded.paste(small, ((padded.width - w) // 2, 0))
    return padded


ICONS = {
    "kSoundOn": sound_on,
    "kSoundOff": sound_off,
    "kNext": next_video,
    "kRepeatOne": repeat_one,
    "kRepeatAll": repeat_all,
}


def main():
    masks = {name: fn().resize((SIZE, SIZE), Image.LANCZOS) for name, fn in ICONS.items()}

    lines = [
        "// Generated by tools/gen_icons.py - do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace icons {",
        "",
        f"constexpr int kSize = {SIZE};",
        "",
    ]
    msg = message()
    lines.append(f"// \"{MESSAGE}\", {msg.width}x{msg.height} alpha.")
    lines.append(f"constexpr int kMessageW = {msg.width};")
    lines.append(f"constexpr int kMessageH = {msg.height};")
    masks_all = dict(masks)
    masks_all["kMessage"] = msg
    for name, img in masks_all.items():
        data = img.tobytes()
        lines.append(f"// {name}: {img.width}x{img.height} alpha, row by row.")
        lines.append(f"constexpr uint8_t {name}[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("}  // namespace icons")
    (ROOT / "main" / "icons.h").write_text("\n".join(lines) + "\n")

    width = max((SIZE + 16) * len(masks) + 16, msg.width + 32)
    preview = Image.new("RGB", (width, SIZE + 48 + msg.height), (0, 0, 0))
    for i, img in enumerate(masks.values()):
        preview.paste((255, 255, 255), (16 + i * (SIZE + 16), 16), img)
    preview.paste((255, 255, 255), ((width - msg.width) // 2, SIZE + 32), msg)
    preview = preview.resize((preview.width * 3, preview.height * 3), Image.NEAREST)
    preview.save(ROOT / "tools" / "icons_preview.png")
    print("wrote main/icons.h and tools/icons_preview.png")


if __name__ == "__main__":
    main()
